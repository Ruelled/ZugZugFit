local function test(name,fn) local ok,err=pcall(fn);if not ok then error(name..': '..tostring(err)) end;tests=tests+1;print('PASS '..name) end
local function equal(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function fixture(day,minute)
    local clock={day=day or '2026-10-23',minute=minute or 0,now=100000}
    local e=assert(C.new({},function() return clock end));return e,clock
end
local function rule(kind)
    return {activity='Push-ups',unit='reps',amount=10,days='1234567',kind=kind or 'daily',at=21*60,interval=1,windowStart=0,windowEnd=1440,trigger='mailbox',cooldown=15,cap=2}
end
local function count(t) local n=0;for _ in pairs(t) do n=n+1 end;return n end
local function goal(e,period) return assert(e:addGoal({activity='Yoga',unit='minutes',amount=15,period=period or 'day',days='1234567'})) end
test('Calendar arithmetic, leap years, weekdays and periods',function()
    equal(C.weekday('2026-10-25'),7);equal(C.weekday('2026-10-26'),1)
    equal(C.addDays('2024-02-28',1),'2024-02-29');equal(C.addDays('2025-03-01',-1),'2025-02-28')
    equal(C.addDays('2026-12-31',1),'2027-01-01');equal(C.parseDay('2026-02-30'),nil)
    local a,b=C.period('2026-10-25','week');equal(a,'2026-10-19');equal(b,'2026-10-25')
    a,b=C.period('2026-05-31','three months');equal(a,'2026-02-28');equal(b,'2026-05-31')
end)
test('Daily schedule once per date, including repeated wall-clock hour',function()
    local e,c=fixture();local r=e:addRule(rule());e:tick(1,false);equal(e:nextPrompt(),nil)
    c.minute=1260;e:tick(1,false);local o=e:nextPrompt();assert(o);e:dismiss(o.id)
    c.minute=1200;e:tick(1,false);c.minute=1260;e:tick(1,false);equal(e:nextPrompt(),nil)
    c.day='2026-10-24';e:tick(1,false);assert(e:nextPrompt());equal(count(e.db.occurrences),2)
    equal(e.db.rules[r.id].enabled,true)
end)

test('Friday backfill updates Friday goal and week, preserves skipped reminder',function()
    local e,c=fixture('2026-10-23',1300);local g=goal(e);local spec=rule();spec.activity='Yoga';spec.unit='minutes';spec.amount=15
    e:addRule(spec);e:tick(1,false);local o=e:nextPrompt();e:dismiss(o.id)
    c.day='2026-10-25';local l=assert(e:saveLog({activity='Yoga',unit='minutes',amount=15,day='2026-10-23'}))
    equal(l.origin,'backfill');equal(o.status,'skipped');equal(e:goalStatus(g,'2026-10-23'),'Completed')
    equal(e:total('Yoga','minutes','2026-10-25','2026-10-25'),0)
    local a,b=C.period(c.day,'week');equal(e:total('Yoga','minutes',a,b),15)
    e:deleteLog(l.id);equal(e:goalStatus(g,'2026-10-23'),'Unmet');e:restoreLog(l.id);equal(e:goalStatus(g,'2026-10-23'),'Completed')
end)
